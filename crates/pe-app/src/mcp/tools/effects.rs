pub fn apply<S>(router: &mut rmcp::handler::server::router::tool::ToolRouter<S>) {
    for (name, route) in router.map.iter_mut() {
        if let Some((_, effect)) = TABLE.iter().find(|(n, _)| *n == name) {
            whirlwind_mcp::policy::classify(&mut route.attr, *effect);
        }
    }
}
